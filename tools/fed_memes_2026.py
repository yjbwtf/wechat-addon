cfg = load_config()
book = MemeBook.load(cfg.memes, ROOT)
before = len(book.entries)
print(f"内置库 {before} 条，开始写入叠加层…\n")

added, updated, dup = 0, 0, []
for term, aliases, note in ENTRIES:
    # 内置库里已有的就别往叠加层塞 —— 塞了会遮蔽内置那条，
    # 之后在 memes.yaml 里改它反而没效果（踩过一次：偷感）。
    if any(e.term == term and e.source == "builtin" for e in book.entries):
        dup.append(term)
        continue
    existed = any(e.term == term and e.source == "user" for e in book.entries)
    r = book.add(term, note, aliases=aliases)
    if r.startswith("记住"):
        if existed:
            updated += 1
        else:
            added += 1
    else:
        print("  失败:", r)

book.reload()
user = [e for e in book.entries if e.source == "user"]
print(f"\n新增 {added} 条，覆盖 {updated} 条，跳过内置已有的 {len(dup)} 条：{dup}")
print(f"现在总计 {len(book.entries)} 条（其中叠加层 {len(user)} 条）")
print()
